#!/usr/bin/env ruby
# Generates src/mql/spec.rs from MongoDB's MQL specifications
# (https://github.com/mongodb/mql-specifications, Apache-2.0):
#
#   git clone --depth 1 https://github.com/mongodb/mql-specifications /tmp/mql
#   ruby scripts/gen-mql.rb /tmp/mql > src/mql/spec.rs
#
# Only what completion and validation need is kept: names, kinds, a one-line
# summary, the docs link and the arguments.
require "yaml"

root = ARGV[0] or abort "usage: gen-mql.rb PATH_TO_MQL_SPECIFICATIONS"
sha = `git -C #{root} rev-parse HEAD`.strip

DIRS = {
  "query" => "Query",
  "stage" => "Stage",
  "expression" => "Expression",
  "accumulator" => "Accumulator",
  "update" => "Update",
}

def rs(s)
  s.to_s.inspect.gsub("\\#", "#")
end

def summary(text)
  line = text.to_s.strip.split("\n").first.to_s
  sentence = line[/\A.*?[.!?](?=\s|\z)/] || line
  sentence.length > 110 ? sentence[0, 107].rstrip + "..." : sentence
end

def type_name(t)
  t.is_a?(Hash) ? t["name"] : t
end

def kinds(dir, types)
  names = types.map { |t| type_name(t) }
  k = []
  case dir
  when "query"
    k << "FIELD_QUERY" if names.include?("fieldQuery")
    k << "QUERY" if names.include?("query")
    k << "GEOMETRY" if names.include?("geometry")
  when "stage"
    k << "STAGE"
    k << "UPDATE_STAGE" if names.include?("updateStage")
  when "expression"
    k << "EXPRESSION"
  when "accumulator"
    k << "ACCUMULATOR" if names.include?("accumulator")
    k << "WINDOW" if names.include?("window")
  when "update"
    k << "UPDATE"
  end
  k.empty? ? ["EXPRESSION"] : k
end

puts "// Generated by scripts/gen-mql.rb from mongodb/mql-specifications@#{sha[0, 12]}"
puts "// (Apache-2.0, see third_party/mql-specifications/LICENSE). Do not edit."
puts
puts "use super::{Arg, Encode, Kind, Op};"
puts
puts "#[rustfmt::skip]"
puts "pub static OPS: &[Op] = &["
DIRS.each_key do |dir|
  Dir["#{root}/definitions/#{dir}/*.yaml"].sort.each do |file|
    d = YAML.load_file(file)
    returns = (d["type"] || []).map { |t| type_name(t) }
      .select { |t| t.start_with?("resolvesTo") }
      .map { |t| t.sub("resolvesTo", "").sub(/\A./) { |c| c.downcase } }
    args = (d["arguments"] || []).map do |a|
      types = (a["type"] || []).map { |t| rs(type_name(t)) }.join(", ")
      variadic = a["variadic"] ? "Some(#{rs(a["variadic"])})" : "None"
      "Arg { name: #{rs(a["name"])}, types: &[#{types}], optional: #{a["optional"] ? "true" : "false"}, variadic: #{variadic} }"
    end
    puts "    Op {"
    puts "        name: #{rs(d["name"])},"
    puts "        kind: Kind(#{kinds(dir, d["type"] || []).map { |k| "Kind::#{k}.0" }.join(" | ")}),"
    puts "        encode: Encode::#{d["encode"].capitalize},"
    puts "        summary: #{rs(summary(d["description"]))},"
    puts "        link: #{rs(d["link"])},"
    puts "        returns: &[#{returns.map { |r| rs(r) }.join(", ")}],"
    puts "        args: &[#{args.empty? ? "" : "\n            " + args.join(",\n            ") + ",\n        "}],"
    puts "    },"
  end
end
puts "];"
